    def test_compact_rate_keeps_one_decimal_only_below_ten(self):
        rate = console_render._compact_rate
        self.assertEqual(rate(3.2e6, True), "3.2Mb")
        self.assertEqual(rate(8e5, True), "800Kb")
        self.assertEqual(rate(44040192, False), "42MB")
        self.assertEqual(rate(8388608, False), "8.0MB")
        self.assertEqual(rate(9.94, False), "9.9B")
        self.assertEqual(rate(9.96, False), "10B")
