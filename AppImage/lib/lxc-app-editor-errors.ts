export function localizeAppEditorError(message: string | null | undefined, t: Translate): string {
  if (!message) return ""
  for (const [pattern, key, names] of RULES) {
    const match = pattern.exec(message)
    if (!match) continue
    const params = Object.fromEntries(names.map((name, index) => [name, match[index + 1]]))
    return t(`vmLxc.appEditor.errors.${key}`, params)
  }
  return message
}
