export function hostBackupErrorText(problem: unknown, t: Translate): string {
  const message = typeof problem === "string" ? problem
    : problem && typeof problem === "object" && "message" in problem && typeof problem.message === "string"
      ? problem.message : ""
  if (!message) return t("backup.apiErrors.requestFailed")
  const key = fixed.get(message)
  if (key) return t(key)
  // Keep unusually large tool output verbatim, without running pattern matching over it.
  if (message.length > 16384) return message
  for (const [pattern, patternKey] of parameterized) {
    const match = pattern.exec(message)
    if (match) return t(patternKey, { value: match[1], other: match[2] ?? "" })
  }
  return message
}
